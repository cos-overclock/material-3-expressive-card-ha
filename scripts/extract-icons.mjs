// Extracts the icon glyphs exported from the FigCraft "Icons" frames into a
// TypeScript icon table. Each icon component sits on a 48px grid, 12 per row,
// and holds a single translated <path>; we move the path back to the icon's
// own 24×24 origin.
//
//   node scripts/extract-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['design-src/icons-1.svg', 'design-src/icons-2.svg'];
const icons = {};

for (const file of sources) {
  const svg = readFileSync(join(root, file), 'utf8');
  const re = /<g id="icon\/(mdi|ms)_([^"]+)">.*?<path transform="matrix\(1 0 0 1 ([-\d.]+) ([-\d.]+)\)" d="([^"]+)"/g;
  let index = 0;
  for (const m of svg.matchAll(re)) {
    const [, set, rawName, tx, ty, d] = m;
    const ox = (index % 12) * 48;
    const oy = Math.floor(index / 12) * 48;
    index += 1;
    const dx = +(Number(tx) - ox).toFixed(3);
    const dy = +(Number(ty) - oy).toFixed(3);
    const name = rawName.replace(/_/g, '-');
    const key = set === 'mdi' ? `mdi-${name}` : name;
    icons[key] = { d, dx, dy };
  }
}

const lines = Object.entries(icons)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  '${k}': { d: '${v.d}', dx: ${v.dx}, dy: ${v.dy} },`);

const out = `// Generated by scripts/extract-icons.mjs from the FigCraft icon frames. Do not edit.
export interface IconGlyph { d: string; dx: number; dy: number }
export const ICONS: Record<string, IconGlyph> = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src/icons/icon-data.ts'), out);
console.log(`${Object.keys(icons).length} icons written`);
