// Icons the design's frames don't include, taken from the same family
// (Material Symbols Rounded, weight 400) in @material-symbols/svg-400.
// Add a name to NAMES and run:
//
//   npm run icons:extra
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAMES = [
  'warning', 'error', 'info', 'cancel',
  // media
  'volume_off', 'volume_down', 'volume_mute', 'input', 'speaker_group', 'cast', 'play_pause', 'fast_forward', 'fast_rewind',
  // fans, purifiers, humidifiers
  'mode_fan_off', 'air_purifier_gen', 'humidity_high', 'humidity_mid', 'sync', 'rotate_right', 'rotate_left', 'tune',
  // controls
  'list', 'expand_all', 'arrow_drop_down', 'keyboard_arrow_left', 'keyboard_arrow_right', 'arrow_back', 'menu', 'apps',
  'radio_button_unchecked', 'check',
  // areas, maintenance
  'meeting_room', 'sensor_occupied', 'door_open', 'battery_alert', 'battery_2_bar', 'battery_5_bar', 'upgrade', 'build',
  'cloud_off', 'link_off',
  // remote, timer
  'settings_remote', 'timer_pause', 'restart_alt', 'replay', 'hourglass_top',
  // weather
  'umbrella', 'thunderstorm', 'foggy', 'weather_snowy', 'snowing', 'clear_day', 'partly_cloudy_night', 'visibility',
  // alarm, vacuum, light, climate
  'shield_lock', 'bedtime', 'flight', 'gpp_bad', 'lock_open', 'blinds_closed', 'my_location', 'wand_stars', 'eco',
  'rocket_launch', 'mode_heat', 'mode_cool', 'thermostat_auto', 'mop', 'home_work',
];

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded');

const lines = NAMES.map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const d = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error(`no path in ${name}.svg`);
  return `  '${name.replace(/_/g, '-')}': { d: '${d}', dx: 0, dy: 0, vb: '0 -960 960 960' },`;
});

const out = `// Generated by scripts/extra-icons.mjs from @material-symbols/svg-400 (rounded). Do not edit.
import type { IconGlyph } from './icon-data';
export const EXTRA_ICONS: Record<string, IconGlyph> = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src/icons/extra-icons.ts'), out);
console.log(`wrote ${NAMES.length} icons to src/icons/extra-icons.ts`);
